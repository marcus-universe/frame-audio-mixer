pub fn effect_name(t: &Text, kind: crate::config::EffectKind) -> &'static str {
    match kind {
        crate::config::EffectKind::Reverb => t.effect_reverb,
        crate::config::EffectKind::Comp => t.effect_comp,
        crate::config::EffectKind::Eq => t.effect_eq,
        crate::config::EffectKind::Pitcher => t.effect_pitcher,
        crate::config::EffectKind::Flanger => t.effect_flanger,
        crate::config::EffectKind::Phaser => t.effect_phaser,
        crate::config::EffectKind::Delay => t.effect_delay,
        crate::config::EffectKind::Vst => t.vst_section,
    }
}

pub fn param_name(t: &Text, kind: crate::config::EffectKind, index: usize) -> &'static str {
    match (kind, index) {
        (crate::config::EffectKind::Reverb, 0) => t.param_size,
        (crate::config::EffectKind::Reverb, 1) => t.param_decay,
        (crate::config::EffectKind::Reverb, 2) => t.param_mix,
        (crate::config::EffectKind::Comp, 0) => t.param_threshold,
        (crate::config::EffectKind::Comp, 1) => t.param_ratio,
        (crate::config::EffectKind::Comp, 2) => t.param_makeup,
        (crate::config::EffectKind::Eq, 0) => t.param_low,
        (crate::config::EffectKind::Eq, 1) => t.param_mid,
        (crate::config::EffectKind::Eq, 2) => t.param_high,
        (crate::config::EffectKind::Pitcher, 0) => t.param_semitones,
        (crate::config::EffectKind::Flanger, 0) | (crate::config::EffectKind::Phaser, 0) => t.param_rate,
        (crate::config::EffectKind::Flanger, 1) | (crate::config::EffectKind::Phaser, 1) => t.param_depth,
        (crate::config::EffectKind::Flanger, 2) | (crate::config::EffectKind::Phaser, 2) => t.param_mix,
        (crate::config::EffectKind::Delay, 0) => t.param_time,
        (crate::config::EffectKind::Delay, 1) => t.param_feedback,
        (crate::config::EffectKind::Delay, 2) => t.param_mix,
        _ => t.param_mix,
    }
}

