pub fn self_test() -> Result<(), String> {
    for lang in LANGS {
        let code = lang.code();
        if parse_code(code) != Some(lang) {
            return Err(code.into());
        }
        let t = text(lang);
        if t.title.is_empty() || t.footer_start.is_empty() || t.apps.is_empty() || t.mute.is_empty() || !t.new_channel_fmt.contains("{name}") || !t.bus_fmt.contains("{color}") {
            return Err(format!("empty {code}"));
        }
    }
    if parse_code("mix").is_some() {
        return Err("mix is not a language".into());
    }
    Ok(())
}
